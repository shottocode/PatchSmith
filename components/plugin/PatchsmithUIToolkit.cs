// Patchsmith - translation of UI Toolkit texts (Unity 6 and later) for BepInEx 5.
// XUnity.AutoTranslator does not see UI Toolkit texts in Unity 6: this plugin replaces the text when the game
// assigns it to a label (TextElement.text), using Patchsmith's ready translations (XUnity's cache,
// BepInEx/Translation/<language>/Text/*.txt). Texts with numbers ("Coins: 123"): the pieces between the numbers
// are translated.
// Compiled by Patchsmith with csc (C# 5).
using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using BepInEx;
using HarmonyLib;

[BepInPlugin("patchsmith.uitoolkit", "Patchsmith UI Toolkit", "1.0.0")]
public class PatchsmithUIToolkit : BaseUnityPlugin
{
    static readonly Dictionary<string, string> Traduzioni = new Dictionary<string, string>();
    static readonly Regex Separatori = new Regex(@"(\d[\d.,]*\s*%?|[\s:;·•|/()\[\]\-+x×#*]+)");
    static BepInEx.Logging.ManualLogSource Registro;
    static readonly HashSet<string> Visti = new HashSet<string>();

    void Awake()
    {
        Registro = Logger;
        string lingua = LinguaXUnity();
        string cartella = Path.Combine(Path.Combine(Path.Combine(Paths.BepInExRootPath, "Translation"), lingua), "Text");
        if (Directory.Exists(cartella))
        {
            foreach (string file in Directory.GetFiles(cartella, "*.txt"))
            {
                if (Path.GetFileName(file).StartsWith("_") && !Path.GetFileName(file).StartsWith("_AutoGenerated"))
                    continue;
                foreach (string riga in File.ReadAllLines(file, Encoding.UTF8))
                    Carica(riga);
            }
        }
        Type tipo = AccessTools.TypeByName("UnityEngine.UIElements.TextElement");
        MethodInfo setter = tipo == null ? null : AccessTools.PropertySetter(tipo, "text");
        if (setter == null)
        {
            Logger.LogWarning("TextElement.text non trovato: niente traduzione di UI Toolkit");
            return;
        }
        new Harmony("patchsmith.uitoolkit").Patch(setter,
            new HarmonyMethod(typeof(PatchsmithUIToolkit).GetMethod("Prima", BindingFlags.Static | BindingFlags.NonPublic)));
        Logger.LogInfo("Traduzioni caricate: " + Traduzioni.Count + " (" + lingua + "), UI Toolkit agganciato");
    }

    static string LinguaXUnity()
    {
        string ini = Path.Combine(Paths.ConfigPath, "AutoTranslatorConfig.ini");
        if (File.Exists(ini))
            foreach (string riga in File.ReadAllLines(ini))
                if (riga.StartsWith("Language="))
                    return riga.Substring(9).Trim();
        return "it";
    }

    static void Carica(string riga)
    {
        if (riga.Length == 0 || riga.StartsWith("//"))
            return;
        int uguale = -1;
        for (int i = 0; i < riga.Length; i++)
        {
            if (riga[i] == '\\') { i++; continue; }
            if (riga[i] == '=') { uguale = i; break; }
        }
        if (uguale <= 0)
            return;
        string chiave = Riprendi(riga.Substring(0, uguale));
        string valore = Riprendi(riga.Substring(uguale + 1));
        if (valore.Length > 0 && !Traduzioni.ContainsKey(chiave))
            Traduzioni[chiave] = valore;
    }

    static string Riprendi(string s)
    {
        StringBuilder b = new StringBuilder(s.Length);
        for (int i = 0; i < s.Length; i++)
        {
            char c = s[i];
            if (c == '\\' && i + 1 < s.Length)
            {
                char d = s[++i];
                if (d == 'n') b.Append('\n');
                else if (d == 'r') b.Append('\r');
                else if (d == 't') b.Append('\t');
                else b.Append(d);
            }
            else b.Append(c);
        }
        return b.ToString();
    }

    static void Prima(ref string value)
    {
        try
        {
            if (!string.IsNullOrEmpty(value))
                value = Traduci(value);
        }
        catch (Exception e)
        {
            if (Registro != null) Registro.LogWarning(e.Message);
        }
    }

    static string Cerca(string t)
    {
        string r;
        if (Traduzioni.TryGetValue(t, out r)) return r;
        string s = t.Trim();
        if (s.Length > 0 && s.Length != t.Length && Traduzioni.TryGetValue(s, out r))
            return t.Substring(0, t.IndexOf(s)) + r + t.Substring(t.IndexOf(s) + s.Length);
        return null;
    }

    static string Traduci(string t)
    {
        string r = Cerca(t);
        if (r != null) return r;
        // pieces between numbers and symbols: "Coins: 1,234" -> "Monete: 1,234"
        string[] pezzi = Separatori.Split(t);
        if (pezzi.Length > 1)
        {
            bool cambiato = false;
            StringBuilder b = new StringBuilder();
            foreach (string p in pezzi)
            {
                string q = null;
                if (p.Length > 1 && !Separatori.IsMatch(p)) q = Cerca(p);
                if (q != null) { b.Append(q); cambiato = true; }
                else b.Append(p);
            }
            if (cambiato) return b.ToString();
        }
        if (Registro != null && Visti.Count < 150 && Visti.Add(t))
            Registro.LogInfo("Senza traduzione: " + t);
        return t;
    }
}
