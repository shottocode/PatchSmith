// Patchsmith - translation of UI Toolkit texts (Unity 6 and later) for BepInEx 5.
// XUnity.AutoTranslator does not see UI Toolkit texts in Unity 6: this plugin replaces the text when the game
// assigns it to a label (TextElement.text), using Patchsmith's ready translations (XUnity's cache,
// BepInEx/Translation/<language>/Text/*.txt). Texts with numbers ("Coins: 123"): the pieces between the numbers
// are translated.
// Compiled by Patchsmith with csc (C# 5).
using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using BepInEx;
using HarmonyLib;

[BepInPlugin("patchsmith.uitoolkit", "Patchsmith UI Toolkit", "1.0.0")]
public class PatchsmithUIToolkit : BaseUnityPlugin
{
    static readonly Dictionary<string, string> Translations = new Dictionary<string, string>();
    static readonly Regex Separators = new Regex(@"(\d[\d.,]*\s*%?|[\s:;·•|/()\[\]\-+x×#*]+)");
    static BepInEx.Logging.ManualLogSource Log;
    static readonly HashSet<string> Seen = new HashSet<string>();

    void Awake()
    {
        Log = Logger;
        string language = XUnityLanguage();
        string folder = Path.Combine(Path.Combine(Path.Combine(Paths.BepInExRootPath, "Translation"), language), "Text");
        if (Directory.Exists(folder))
        {
            foreach (string file in Directory.GetFiles(folder, "*.txt"))
            {
                if (Path.GetFileName(file).StartsWith("_") && !Path.GetFileName(file).StartsWith("_AutoGenerated"))
                    continue;
                foreach (string line in File.ReadAllLines(file, Encoding.UTF8))
                    Load(line);
            }
        }
        Type type = AccessTools.TypeByName("UnityEngine.UIElements.TextElement");
        MethodInfo setter = type == null ? null : AccessTools.PropertySetter(type, "text");
        if (setter == null)
        {
            Logger.LogWarning("TextElement.text not found: no translation of UI Toolkit");
            return;
        }
        new Harmony("patchsmith.uitoolkit").Patch(setter,
            new HarmonyMethod(typeof(PatchsmithUIToolkit).GetMethod("Prefix", BindingFlags.Static | BindingFlags.NonPublic)));
        Logger.LogInfo("Translations loaded: " + Translations.Count + " (" + language + "), UI Toolkit hooked");
    }

    static string XUnityLanguage()
    {
        string ini = Path.Combine(Paths.ConfigPath, "AutoTranslatorConfig.ini");
        if (File.Exists(ini))
            foreach (string line in File.ReadAllLines(ini))
                if (line.StartsWith("Language="))
                    return line.Substring(9).Trim();
        return "it";
    }

    static void Load(string line)
    {
        if (line.Length == 0 || line.StartsWith("//"))
            return;
        int equals = -1;
        for (int i = 0; i < line.Length; i++)
        {
            if (line[i] == '\\') { i++; continue; }
            if (line[i] == '=') { equals = i; break; }
        }
        if (equals <= 0)
            return;
        string key = Unescape(line.Substring(0, equals));
        string value = Unescape(line.Substring(equals + 1));
        if (value.Length > 0 && !Translations.ContainsKey(key))
            Translations[key] = value;
    }

    static string Unescape(string s)
    {
        StringBuilder b = new StringBuilder(s.Length);
        for (int i = 0; i < s.Length; i++)
        {
            char c = s[i];
            if (c == '\\' && i + 1 < s.Length)
            {
                char d = s[++i];
                if (d == 'n') b.Append('\n');
                else if (d == 'r') b.Append('\r');
                else if (d == 't') b.Append('\t');
                else b.Append(d);
            }
            else b.Append(c);
        }
        return b.ToString();
    }

    static void Prefix(ref string value)
    {
        try
        {
            if (!string.IsNullOrEmpty(value))
                value = Translate(value);
        }
        catch (Exception e)
        {
            if (Log != null) Log.LogWarning(e.Message);
        }
    }

    static string Find(string t)
    {
        string r;
        if (Translations.TryGetValue(t, out r)) return r;
        string s = t.Trim();
        if (s.Length > 0 && s.Length != t.Length && Translations.TryGetValue(s, out r))
            return t.Substring(0, t.IndexOf(s)) + r + t.Substring(t.IndexOf(s) + s.Length);
        return null;
    }

    static string Translate(string t)
    {
        string r = Find(t);
        if (r != null) return r;
        // pieces between numbers and symbols: "Coins: 1,234" -> "Monete: 1,234"
        string[] pieces = Separators.Split(t);
        if (pieces.Length > 1)
        {
            bool changed = false;
            StringBuilder b = new StringBuilder();
            foreach (string p in pieces)
            {
                string q = null;
                if (p.Length > 1 && !Separators.IsMatch(p)) q = Find(p);
                if (q != null) { b.Append(q); changed = true; }
                else b.Append(p);
            }
            if (changed) return b.ToString();
        }
        if (Log != null && Seen.Count < 150 && Seen.Add(t))
            Log.LogInfo("No translation: " + t);
        return t;
    }
}
