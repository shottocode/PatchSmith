    os.makedirs(os.path.dirname(_path(folder, SERVICE_CONFIG)), exist_ok=True)
    write_atomic(_path(folder, SERVICE_CONFIG), ("\r\n".join(lines) + "\r\n").encode("utf-8"))
    return xunity_service.address(port)


