"""Unity (Mono) adapter: installs and configures BepInEx 5 + XUnity.AutoTranslator.

XUnity translates the texts WHILE the game runs (UGUI, TextMeshPro, IMGUI...): the sentences it does not find already
translated it asks PatchSmith's translator for (servizio_xunity, started by the PatchsmithServizio plugin when the
game opens), which uses the game's translation memory and the checks and pauses of PatchSmith's translators. Only if
the plugin cannot be prepared (e.g. the Windows C# compiler is missing) does XUnity use free Google by itself, and
never while Google is paused because of a block. The translations stay in
BepInEx/Translation/<lingua>/Text/_AutoGeneratedTranslations.txt (originale=traduzione).
A sentence seen for the first time appears untranslated for a moment, then translated; from the next time on it is
immediate.

Safety:
- it never touches the game's files: it only adds new files (BepInEx/, winhttp.dll, doorstop_config.ini...);
- if it finds a mod loader already there (BepInEx, MelonLoader, winhttp.dll/version.dll...) it stops;
- the components come from the official releases with a verified SHA-256 fingerprint (components.py);
- BEFORE writing it saves in patchsmith-unity.json the full list of files with their fingerprints;
- each file is written under a temporary name and then renamed (no half-written files);
- if the installation is interrupted, it removes everything it had planned to put in;
- the uninstall removes ONLY the files put there by us and those created by BepInEx/XUnity; everything else (e.g.
  mods added by the user) stays in place and is reported;
- the manifest is validated before using it to delete anything.
"""
